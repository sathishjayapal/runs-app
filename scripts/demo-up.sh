#!/usr/bin/env bash
set -euo pipefail

#################################################################
# runs-app local DEMO: synthetic data you can screenshot, screen-record or show.
#
# Usage:  scripts/demo-up.sh            start (or resume) the demo
#         scripts/demo-down.sh          stop it (add --wipe to delete the demo data)
#
# What it does:
#   1. Starts its OWN Postgres (127.0.0.1:5543) and its OWN RabbitMQ (127.0.0.1:5673), both in
#      containers with private volumes/credentials. runs-app refuses to start without a broker that
#      accepts its login, so it gets one that is separate from your real local stack on 5672.
#   2. Writes .env.demo.local with freshly generated random passwords (git-ignored, mode 600).
#   3. Starts runs-app (sample login users enabled) on http://localhost:$DEMO_APP_PORT (default 8080).
#   4. Loads scripts/demo-seed.sql: 48 fictional Garmin runs and 8 Strava runs.
#
# Safety: it never reads or writes .env, never uses the dev database on 5443 or the broker on 5672,
# and never talks to the VM. Google Drive import and the AI analyzer are off, so the AI Insights
# page shows its "service unavailable" message; every other page works.
#
# Override with environment variables: DEMO_APP_PORT (8080), DEMO_PG_PORT (5543), DEMO_MQ_PORT (5673).
#################################################################

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

DEMO_APP_PORT="${DEMO_APP_PORT:-8080}"
DEMO_PG_PORT="${DEMO_PG_PORT:-5543}"
DEMO_MQ_PORT="${DEMO_MQ_PORT:-5673}"
PG_CONTAINER="runs-app-demo-postgres"
PG_VOLUME="runs-app-demo-pgdata"
MQ_CONTAINER="runs-app-demo-rabbitmq"
DB_NAME="runsapp_demo"
DB_USER="runsapp_demo"
ENV_FILE="$ROOT/.env.demo.local"
LOG_FILE="$ROOT/target/demo-app.log"
PID_FILE="$ROOT/target/demo-app.pid"
DEMO_LOGIN="runner@runsapp.com"

say()  { printf '\033[0;32m✓\033[0m %s\n' "$*"; }
info() { printf '\033[1;33mℹ\033[0m %s\n' "$*"; }
die()  { printf '\033[0;31m✗\033[0m %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || die "docker not found"
docker info >/dev/null 2>&1 || die "Docker is not running"

port_in_use() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }
# No pipe into grep -q here: under pipefail an early-exiting grep can make the pipeline report failure.
container_exists() { [ -n "$(docker ps -a --filter "name=^${1}\$" --format '{{.Names}}')" ]; }

# Java 21 (the project target); JDK 23+ no longer runs Lombok from the classpath by default.
if [ -x /usr/libexec/java_home ]; then
  J21="$(/usr/libexec/java_home -v 21 2>/dev/null || true)"
  [ -n "$J21" ] && export JAVA_HOME="$J21"
fi

# --- 1. isolated Postgres -------------------------------------------------
if [ ! -f "$ENV_FILE" ]; then
  # Reusing an old volume with a new password would fail to log in, so refuse that combination.
  if docker volume inspect "$PG_VOLUME" >/dev/null 2>&1; then
    die "Volume $PG_VOLUME exists but $ENV_FILE is missing. Run scripts/demo-down.sh --wipe first."
  fi
  rand() { openssl rand -hex 12; }
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/demo-up.sh. Local demo only; never commit (the .env.*.local rule ignores it).
# pom.xml pins spring-boot:run to the "local" profile, which beats SPRING_PROFILES_ACTIVE, so the demo
# users are switched on with the explicit variables below instead of the "dev" profile.
APP_INITIALIZATION_ENABLE_SAMPLE_DATA=true
APP_INITIALIZATION_ADMIN_EMAIL=admin@runsapp.com
APP_INITIALIZATION_USER_EMAIL=runner@runsapp.com
APP_INITIALIZATION_SYSTEM_EMAIL=system@runsapp.com
SERVER_PORT=${DEMO_APP_PORT}
BASE_HOST=http://localhost:${DEMO_APP_PORT}
CORS_ALLOWED_ORIGINS=http://localhost:3000,http://localhost:${DEMO_APP_PORT}
JDBC_DATABASE_URL=jdbc:postgresql://localhost:${DEMO_PG_PORT}/${DB_NAME}
JDBC_DATABASE_USERNAME=${DB_USER}
JDBC_DATABASE_PASSWORD=$(rand)
APP_INITIALIZATION_ADMIN_PASSWORD=$(rand)
APP_INITIALIZATION_USER_PASSWORD=$(rand)
APP_INITIALIZATION_SYSTEM_PASSWORD=$(rand)
GARMIN_CSV_IMPORT_ENABLED=false
GARMIN_CSV_IMPORT_SCHEDULE="0 0 3 * * *"
GARMIN_SYSTEM_USER_ID=10000
RABBITMQ_HOST=localhost
RABBITMQ_PORT=${DEMO_MQ_PORT}
RABBITMQ_USERNAME=demo
RABBITMQ_PASSWORD=$(rand)
RUNS_AI_ANALYZER_URL=http://localhost:9
SMTP_USERNAME=unused
SMTP_PASSWORD=unused
# No mail server in the demo: without this the mail health check fails and /actuator/health reports DOWN.
MANAGEMENT_HEALTH_MAIL_ENABLED=false
EOF
  say "Wrote $ENV_FILE with generated passwords"
fi

set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a

if container_exists "$PG_CONTAINER"; then
  docker start "$PG_CONTAINER" >/dev/null
  say "Demo Postgres resumed"
else
  port_in_use "$DEMO_PG_PORT" && die "Port $DEMO_PG_PORT is busy; set DEMO_PG_PORT to a free port"
  docker run -d --name "$PG_CONTAINER" \
    -p "127.0.0.1:${DEMO_PG_PORT}:5432" \
    -e POSTGRES_DB="$DB_NAME" -e POSTGRES_USER="$DB_USER" -e POSTGRES_PASSWORD="$JDBC_DATABASE_PASSWORD" \
    -v "$PG_VOLUME:/var/lib/postgresql/data" \
    postgres:17 >/dev/null
  say "Demo Postgres started on 127.0.0.1:${DEMO_PG_PORT}"
fi
for _ in $(seq 1 60); do
  docker exec "$PG_CONTAINER" pg_isready -U "$DB_USER" -d "$DB_NAME" >/dev/null 2>&1 && break
  sleep 1
done
docker exec "$PG_CONTAINER" pg_isready -U "$DB_USER" -d "$DB_NAME" >/dev/null 2>&1 || die "Postgres did not become ready"

# --- 1b. isolated RabbitMQ ---------------------------------------------------
if container_exists "$MQ_CONTAINER"; then
  docker start "$MQ_CONTAINER" >/dev/null
  say "Demo RabbitMQ resumed"
else
  port_in_use "$DEMO_MQ_PORT" && die "Port $DEMO_MQ_PORT is busy; set DEMO_MQ_PORT to a free port"
  docker run -d --name "$MQ_CONTAINER" \
    -p "127.0.0.1:${DEMO_MQ_PORT}:5672" \
    -e RABBITMQ_DEFAULT_USER="$RABBITMQ_USERNAME" -e RABBITMQ_DEFAULT_PASS="$RABBITMQ_PASSWORD" \
    rabbitmq:3-management-alpine >/dev/null
  say "Demo RabbitMQ started on 127.0.0.1:${DEMO_MQ_PORT}"
fi
# Wait on the broker's own log line. Do NOT probe with "docker exec rabbitmq-diagnostics": it runs as
# root, whose home in this image is /var/lib/rabbitmq, so an early probe creates a root-owned
# .erlang.cookie there and the broker (running as "rabbitmq") then dies with eacces.
# (Capture then match: "docker logs | grep -q" under pipefail reports failure when grep exits early.)
mq_ready() {
  local out
  out="$(docker logs "$MQ_CONTAINER" 2>&1 || true)"
  case "$out" in *"Server startup complete"*) return 0 ;; esac
  return 1
}
for _ in $(seq 1 120); do
  mq_ready && break
  [ "$(docker inspect -f '{{.State.Running}}' "$MQ_CONTAINER" 2>/dev/null)" = "true" ] || \
    die "RabbitMQ container stopped; see: docker logs $MQ_CONTAINER"
  sleep 1
done
mq_ready || die "RabbitMQ did not become ready"

# runs-app aborts at startup unless the Garmin queues exist: in production eventstracker creates them
# (see RabbitMQConfiguration.garminQueueValidator). Recreate the same topology in the demo broker.
# rabbitmqadmin is an HTTP client, so unlike rabbitmqctl it does not touch the Erlang cookie.
mq_admin() { docker exec "$MQ_CONTAINER" rabbitmqadmin -u "$RABBITMQ_USERNAME" -p "$RABBITMQ_PASSWORD" "$@" >/dev/null; }
GARMIN_XCHG="x.sathishprojects.garmin.events.exchange"
for _ in $(seq 1 30); do
  mq_admin declare exchange name="$GARMIN_XCHG" type=topic durable=true && break
  sleep 1
done
mq_admin declare exchange name="$GARMIN_XCHG" type=topic durable=true || die "Could not talk to the RabbitMQ management API"
for kind in api ops; do
  mq_admin declare queue name="q.sathishprojects.garmin.${kind}.events" durable=true
  mq_admin declare binding source="$GARMIN_XCHG" destination_type=queue \
    destination="q.sathishprojects.garmin.${kind}.events" routing_key="sathishprojects.garmin.${kind}.*"
done
say "Demo RabbitMQ ready with the Garmin queues"

# --- 2. the app ------------------------------------------------------------
if curl -fs -m 3 "http://localhost:${DEMO_APP_PORT}/actuator/health/readiness" >/dev/null 2>&1; then
  info "Something already answers on port ${DEMO_APP_PORT}; assuming it is the demo app"
else
  port_in_use "$DEMO_APP_PORT" && die "Port ${DEMO_APP_PORT} is busy; set DEMO_APP_PORT to a free port"
  mkdir -p "$ROOT/target"
  info "Starting runs-app (first start builds the frontend; this can take a few minutes). Log: $LOG_FILE"
  nohup ./mvnw -B spring-boot:run > "$LOG_FILE" 2>&1 &
  echo $! > "$PID_FILE"
  for _ in $(seq 1 180); do
    curl -fs -m 3 "http://localhost:${DEMO_APP_PORT}/actuator/health/readiness" >/dev/null 2>&1 && break
    kill -0 "$(cat "$PID_FILE")" 2>/dev/null || { tail -n 30 "$LOG_FILE" >&2; die "The app exited early; see $LOG_FILE"; }
    sleep 2
  done
  curl -fs -m 3 "http://localhost:${DEMO_APP_PORT}/actuator/health/readiness" >/dev/null 2>&1 || die "The app did not come up in time; see $LOG_FILE"
  say "runs-app is up"
fi

# --- 3. seed ---------------------------------------------------------------
# The app creates the demo users after the web server is already listening, so wait for them.
for _ in $(seq 1 60); do
  n="$(docker exec "$PG_CONTAINER" psql -U "$DB_USER" -d "$DB_NAME" -tAc \
        "select count(*) from run_app_user where email = '${DEMO_LOGIN}'" 2>/dev/null || echo 0)"
  [ "${n:-0}" = "1" ] && break
  sleep 1
done
[ "${n:-0}" = "1" ] || die "Demo user ${DEMO_LOGIN} was not created"
docker exec -i "$PG_CONTAINER" psql -U "$DB_USER" -d "$DB_NAME" -v ON_ERROR_STOP=1 -q < "$ROOT/scripts/demo-seed.sql"
runs="$(docker exec "$PG_CONTAINER" psql -U "$DB_USER" -d "$DB_NAME" -tAc "select count(*) from garmin_run")"
say "Demo data loaded: ${runs} Garmin runs"

echo
echo "  Demo ready:  http://localhost:${DEMO_APP_PORT}"
echo "  Log in as:   ${DEMO_LOGIN}   (password: APP_INITIALIZATION_USER_PASSWORD in .env.demo.local)"
echo "  Admin login: admin@runsapp.com (APP_INITIALIZATION_ADMIN_PASSWORD in the same file)"
echo "  Stop with:   scripts/demo-down.sh   (add --wipe to delete the demo data)"
