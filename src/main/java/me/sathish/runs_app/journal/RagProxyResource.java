package me.sathish.runs_app.journal;

import java.time.Duration;
import java.util.Map;
import lombok.extern.slf4j.Slf4j;
import me.sathish.runs_app.security.UserRoles;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.client.JdkClientHttpRequestFactory;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.client.HttpStatusCodeException;
import org.springframework.web.client.RestClient;
import org.springframework.web.util.UriBuilder;

@RestController
@RequestMapping(value = "/api/rag", produces = MediaType.APPLICATION_JSON_VALUE)
@PreAuthorize("hasAnyAuthority('" + UserRoles.ROLE_ADMIN + "', '" + UserRoles.ROLE_USER + "')")
@Slf4j
public class RagProxyResource {

    /**
     * The coach answer is generated by an LLM. On the home VM's CPU-only Ollama (no AVX2) a full answer took
     * almost 7 minutes before the prompt was trimmed, so allow well past that: a proxy that gives up first
     * only wastes the generation that is still running.
     */
    private static final Duration ASK_READ_TIMEOUT = Duration.ofMinutes(10);

    private final RestClient restClient;
    private final RestClient askClient;

    public RagProxyResource(
            @Value("${runs-ai-analyzer.base-url}") final String analyzerBaseUrl) {
        this.restClient = RestClient.builder().baseUrl(analyzerBaseUrl).build();
        final JdkClientHttpRequestFactory askFactory = new JdkClientHttpRequestFactory();
        askFactory.setReadTimeout(ASK_READ_TIMEOUT);
        this.askClient = RestClient.builder().baseUrl(analyzerBaseUrl).requestFactory(askFactory).build();
    }

    /**
     * POST /api/rag/ask
     * Body: { "query": "..." }
     * Proxies to runs-ai-analyzer POST /api/v1/rag/ask, which retrieves the runner's analyses and journal
     * entries and has the LLM answer with next steps. Returns { answer, sources, query } or { error }.
     * If the analyzer cannot be reached the reply is 200 with an "error" text, which the page shows in the
     * answer card, rather than a 5xx that sends the user to the generic error screen.
     */
    @PostMapping(value = "/ask", consumes = MediaType.APPLICATION_JSON_VALUE)
    public ResponseEntity<Object> ask(@RequestBody final Object body) {
        try {
            return askClient.post()
                    .uri("/api/v1/rag/ask")
                    .contentType(MediaType.APPLICATION_JSON)
                    .body(body)
                    .retrieve()
                    .toEntity(Object.class);
        } catch (final HttpStatusCodeException e) {
            return ResponseEntity.status(e.getStatusCode()).body(e.getResponseBodyAsString());
        } catch (final Exception e) {
            log.error("RAG ask proxy failed: {}", e.getMessage());
            return ResponseEntity.ok(Map.of("error", "The AI coach is not reachable right now. Please try again shortly."));
        }
    }

    /**
     * POST /api/rag/search
     * Body: { "query": "..." }
     * Proxies to runs-ai-analyzer POST /api/v1/rag/search
     */
    @PostMapping(value = "/search", consumes = MediaType.APPLICATION_JSON_VALUE)
    public ResponseEntity<Object> search(@RequestBody final Object body) {
        return forward(HttpMethod.POST, "/api/v1/rag/search", body);
    }

    /**
     * GET /api/rag/recent
     * Returns the most recent AI analyses stored in vector store.
     * Proxies to runs-ai-analyzer GET /api/v1/rag/recent
     */
    @GetMapping("/recent")
    public ResponseEntity<Object> recent() {
        return forward(HttpMethod.GET, "/api/v1/rag/recent", null);
    }

    /**
     * POST /api/rag/analyze
     * Body: { "runs": [...], "forceRefresh": false }
     * Proxies to runs-ai-analyzer POST /api/v1/analysis/analyze/async
     * Returns immediately with { jobId, status, message }
     */
    @PostMapping(value = "/analyze", consumes = MediaType.APPLICATION_JSON_VALUE)
    public ResponseEntity<Object> submitAnalysis(@RequestBody final Object body) {
        return forward(HttpMethod.POST, "/api/v1/analysis/analyze/async", body);
    }

    /**
     * GET /api/rag/analyze/status/{jobId}
     * Proxies to runs-ai-analyzer GET /api/v1/analysis/analyze/status/{jobId}
     */
    @GetMapping("/analyze/status/{jobId}")
    public ResponseEntity<Object> analysisStatus(@PathVariable final String jobId) {
        return forward(HttpMethod.GET, "/api/v1/analysis/analyze/status/" + jobId, null);
    }

    /**
     * GET /api/rag/analyze/result/{jobId}
     * Proxies to runs-ai-analyzer GET /api/v1/analysis/analyze/result/{jobId}
     */
    @GetMapping("/analyze/result/{jobId}")
    public ResponseEntity<Object> analysisResult(@PathVariable final String jobId) {
        return forward(HttpMethod.GET, "/api/v1/analysis/analyze/result/" + jobId, null);
    }

    @PostMapping(value = "/analysis/{documentId}/diagram", consumes = MediaType.APPLICATION_JSON_VALUE)
    public ResponseEntity<Object> generateDiagram(
            @PathVariable final String documentId,
            @RequestBody final Object body) {
        return forward(HttpMethod.POST, "/api/v1/analysis/" + documentId + "/diagram", body);
    }

    @GetMapping(value = "/diagrams/{fileName}", produces = {
            MediaType.IMAGE_PNG_VALUE,
            MediaType.IMAGE_JPEG_VALUE,
            "image/svg+xml"
    })
    public ResponseEntity<?> downloadDiagram(@PathVariable final String fileName) {
        try {
            final ResponseEntity<byte[]> upstream = restClient.get()
                    .uri(uriBuilder -> uriBuilder.path("/api/v1/analysis/diagrams/{fileName}").build(fileName))
                    .accept(MediaType.IMAGE_PNG, MediaType.IMAGE_JPEG, MediaType.valueOf("image/svg+xml"))
                    .retrieve()
                    .toEntity(byte[].class);
            final HttpHeaders headers = new HttpHeaders();
            if (upstream.getHeaders().getContentType() != null) {
                headers.setContentType(upstream.getHeaders().getContentType());
            }
            if (upstream.getHeaders().getContentDisposition() != null) {
                headers.setContentDisposition(upstream.getHeaders().getContentDisposition());
            }
            if (upstream.getBody() != null) {
                headers.setContentLength(upstream.getBody().length);
            }
            return new ResponseEntity<>(upstream.getBody(), headers, upstream.getStatusCode());
        } catch (final HttpStatusCodeException e) {
            return ResponseEntity.status(e.getStatusCode()).body(e.getResponseBodyAsByteArray());
        } catch (final Exception e) {
            log.error("Diagram download proxy failed for {}: {}", fileName, e.getMessage());
            return ResponseEntity.status(HttpStatus.SERVICE_UNAVAILABLE).build();
        }
    }

    private ResponseEntity<Object> forward(final HttpMethod method, final String path, final Object body) {
        try {
            final RestClient.RequestBodySpec spec = restClient.method(method)
                    .uri(path)
                    .contentType(MediaType.APPLICATION_JSON);
            if (body != null) {
                spec.body(body);
            }
            return spec.retrieve().toEntity(Object.class);
        } catch (final HttpStatusCodeException e) {
            return ResponseEntity.status(e.getStatusCode()).body(e.getResponseBodyAsString());
        } catch (final Exception e) {
            log.error("RAG proxy failed {} {}: {}", method, path, e.getMessage());
            return ResponseEntity.status(HttpStatus.SERVICE_UNAVAILABLE)
                    .body("{\"answer\":\"AI service is currently unavailable. Make sure runs-ai-analyzer is running on port 8081.\"}");
        }
    }

}
