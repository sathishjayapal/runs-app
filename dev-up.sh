SMTP_USERNAME=your-email@gmail.com
SMTP_PASSWORD=your-app-password

# Email Display Settings
MAIL_FROM=noreply@example.com
MAIL_DISPLAY_NAME=Runs App

# Garmin CSV Import Alert Configuration
GARMIN_ALERT_EMAIL_ENABLED=true
GARMIN_ALERT_EMAIL_MAX_RETRY_ATTEMPTS=3
GARMIN_ALERT_EMAIL_RECIPIENTS=admin@example.com,devops@example.com
GARMIN_ALERT_EMAIL_FROM=garmin-import@example.com

# Google Drive Extended Configuration (for quarantine/retry)
GARMIN_DRIVE_FOLDER_ID=your-id
GARMIN_DRIVE_PROCESSED_FOLDER_ID=your_id_val
GARMIN_DRIVE_QUARANTINE_FOLDER_ID=your-quarantine-folder-id
GARMIN_DRIVE_FAILED_FOLDER_ID=your-failed-folder-id
GARMIN_DRIVE_RETRY_FOLDER_ID=your-retry-folder-id

# Sample Data Initialization (Dev Only)
# Enable sample data for local development with: ./mvnw spring-boot:run -Dspring-boot.run.profiles=dev
# See SECURITY_CONFIGURATION.md for more details
APP_INITIALIZATION_ENABLE_SAMPLE_DATA=false
APP_INITIALIZATION_ADMIN_EMAIL=admin@runsapp.com
APP_INITIALIZATION_ADMIN_PASSWORD=dev-admin-password
APP_INITIALIZATION_USER_EMAIL=runner@runsapp.com
APP_INITIALIZATION_USER_PASSWORD=dev-runner-password
APP_INITIALIZATION_SYSTEM_EMAIL=system@runsapp.com
APP_INITIALIZATION_SYSTEM_PASSWORD=dev-system-password

# Production flag
PRODUCTION=false
API_PATH=
EOF

cat << EOF > .env.development
# Runs App Database Configuration
# Generated by dev-up.sh - do not commit to git

# Database Connection
JDBC_DATABASE_NAME=$DB_NAME
JDBC_DATABASE_URL=jdbc:postgresql://localhost:$HOST_PORT/$DB_NAME
JDBC_DATABASE_USERNAME=$DB_USER
JDBC_DATABASE_PASSWORD=$DB_PASSWORD

# RabbitMQ (from infrastructure config)
RABBITMQ_HOST=localhost
RABBITMQ_PORT=5672
RABBITMQ_USERNAME=$RABBITMQ_USER
RABBITMQ_PASSWORD=$RABBITMQ_PASS

# Application Server
SERVER_PORT=$APP_PORT

# Garmin Import Configuration
GARMIN_IMPORT_FOLDER=/data/garmin-fit-files
GARMIN_SYSTEM_USER_ID=10000

# SMTP Configuration (optional - for email features)
SMTP_HOST=smtp.gmail.com
SMTP_USERNAME=your-email@gmail.com
SMTP_PASSWORD=your-app-password

# Email Display Settings
MAIL_FROM=noreply@example.com
MAIL_DISPLAY_NAME=Runs App

# Garmin CSV Import Alert Configuration
GARMIN_ALERT_EMAIL_ENABLED=true
GARMIN_ALERT_EMAIL_MAX_RETRY_ATTEMPTS=3
GARMIN_ALERT_EMAIL_RECIPIENTS=admin@example.com,devops@example.com
GARMIN_ALERT_EMAIL_FROM=garmin-import@example.com

# Google Drive Extended Configuration (for quarantine/retry)
GARMIN_DRIVE_QUARANTINE_FOLDER_ID=your-quarantine-folder-id
GARMIN_DRIVE_FAILED_FOLDER_ID=your-failed-folder-id
GARMIN_DRIVE_RETRY_FOLDER_ID=your-retry-folder-id

# Sample Data Initialization (Dev Only)
# Enable sample data for local development with: ./mvnw spring-boot:run -Dspring-boot.run.profiles=dev
# See SECURITY_CONFIGURATION.md for more details
APP_INITIALIZATION_ENABLE_SAMPLE_DATA=false
APP_INITIALIZATION_ADMIN_EMAIL=admin@runsapp.com
APP_INITIALIZATION_ADMIN_PASSWORD=dev-admin-password
APP_INITIALIZATION_USER_EMAIL=runner@runsapp.com
APP_INITIALIZATION_USER_PASSWORD=dev-runner-password
APP_INITIALIZATION_SYSTEM_EMAIL=system@runsapp.com
APP_INITIALIZATION_SYSTEM_PASSWORD=dev-system-password

# Production flag
PRODUCTION=false
API_PATH=http://localhost:$APP_PORT
EOF

print_status ".env and .env.development files created"
print_info "If this project is deployed to VM/ACG/prod, re-sync: consolidated-postgres/scripts/vm/vm-db-up.sh runs-app"

LOCAL_INFRA_DIR="$(resolve_local_infra)" || {
  print_error "Cannot find consolidated-postgres — clone it as a sibling of runs-app"
  exit 1
}
LOCAL_COMPOSE_FILE="$LOCAL_INFRA_DIR/compose/docker-compose-local.yml"
LOCAL_ENV_FILE="$LOCAL_INFRA_DIR/env/.env.local"
compose() {
  docker compose -f "$LOCAL_COMPOSE_FILE" --env-file "$LOCAL_ENV_FILE" --profile runs-app "$@"
}

# Handle reset flag
# NOTE: this compose file is shared across projects (eventstracker, runs-ai-analyzer,
# mytracker, rabbitmq all live in it too) — never `compose down -v` here, that would
# wipe every sibling project's data. Only touch the runs-app-db service specifically.
if [ "$RESET_DB" = true ]; then
  print_info "Resetting database (--reset flag set)..."
  if docker container inspect "$CONTAINER_NAME" > /dev/null 2>&1; then
    compose rm -f -s -v runs-app-db
    docker volume rm runs-app_postgres-data 2>/dev/null || true
    print_status "Database reset"
  fi
fi

# Start Docker container
print_info "Starting PostgreSQL container..."
if docker container inspect "$CONTAINER_NAME" > /dev/null 2>&1 && docker ps --filter "name=$CONTAINER_NAME" | grep -q "$CONTAINER_NAME"; then
  print_status "PostgreSQL already running on port $HOST_PORT"
else
  compose up -d runs-app-db
  print_status "PostgreSQL started"
fi

# Wait for PostgreSQL to be ready
print_info "Waiting for PostgreSQL to be ready..."
max_attempts=30
attempt=0
_superuser=""

while [ $attempt -lt $max_attempts ]; do
  for _candidate in "$DB_USER" "${EVENTS_TRACKER_DB_USER:-}" "eventsvc_local" "postgres"; do
    [ -n "$_candidate" ] || continue
    if run_psql_with_retry "$_candidate" "postgres" "SELECT 1;" 1; then
      _superuser="$_candidate"
      print_status "PostgreSQL is ready"
      break 2
    fi
  done
  attempt=$((attempt + 1))
  sleep 1
done

if [ $attempt -eq $max_attempts ]; then
  print_error "PostgreSQL failed to start within ${max_attempts}s"
  print_info "Check logs with: docker logs $CONTAINER_NAME"
  exit 1
fi

[ -n "$_superuser" ] || {
  print_error "Could not find a working admin role in $CONTAINER_NAME"
  print_info "If this is an old volume with stale credentials, run: ./dev-up.sh --reset"
  exit 1
}

print_info "Container superuser: '${_superuser}', desired DB user: '${DB_USER}'"
run_psql_with_retry "$_superuser" "postgres" \
  "DO \$\$
   BEGIN
     CREATE ROLE \"${DB_USER}\" LOGIN PASSWORD '${DB_PASSWORD}';
   EXCEPTION WHEN duplicate_object THEN NULL;
   END \$\$;" 30 || {
  print_error "Failed to create/sync DB role ${DB_USER}"
  exit 1
}
run_psql_with_retry "$_superuser" "postgres" \
  "ALTER ROLE \"${DB_USER}\" WITH LOGIN PASSWORD '${DB_PASSWORD}';" 30 || {
  print_error "Failed to update password for DB role ${DB_USER}"
  exit 1
}
run_psql_with_retry "$_superuser" "postgres" \
  "GRANT ALL PRIVILEGES ON DATABASE \"${DB_NAME}\" TO \"${DB_USER}\";" 30 || true

# Verify database exists
print_info "Verifying database..."
if run_psql_with_retry "$DB_USER" "$DB_NAME" "SELECT 1;" 10; then
  print_status "Database verified"
else
  print_error "Failed to verify database"
  exit 1
fi

# Print next steps
echo ""
echo "════════════════════════════════════════════════════════════════"
