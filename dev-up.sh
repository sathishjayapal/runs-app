#!/usr/bin/env bash
set -euo pipefail

#################################################################
# Runs App Development Environment Startup
#
# Usage: ./dev-up.sh [options]
#
# Options:
#   --reset     Drop and recreate database (clean slate)
#   --help      Show this help message
#
# What it does:
#   1. Starts PostgreSQL in Docker
#   2. Waits for database to be ready
#   3. Creates/updates .env file with connection details
#   4. Runs Flyway migrations automatically (when app starts)
#
# Next steps:
#   mvn spring-boot:run
#   or use your IDE's "Run" button
#################################################################

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

# Configuration
CONTAINER_NAME="runs-app-postgres"
DB_NAME="runsapp_db"
DB_USER="postgres"
DB_PASSWORD="P4ssword!"
DB_PORT=5443
HOST_PORT=5443
APP_PORT=8080

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Parse arguments
RESET_DB=false
while [[ $# -gt 0 ]]; do
  case $1 in
    --reset)
      RESET_DB=true
      shift
      ;;
    --help)
      head -n 20 "$0" | tail -n +2
      exit 0
      ;;
    *)
      echo "Unknown option: $1"
      exit 1
      ;;
  esac
done

print_status() {
  echo -e "${GREEN}✓${NC} $1"
}

print_error() {
  echo -e "${RED}✗${NC} $1"
}

print_info() {
  echo -e "${YELLOW}ℹ${NC} $1"
}

# Check if Docker is running
if ! docker ps > /dev/null 2>&1; then
  print_error "Docker is not running. Please start Docker and try again."
  exit 1
fi

print_info "Starting Runs App development environment..."

# Handle reset flag
if [ "$RESET_DB" = true ]; then
  print_info "Resetting database (--reset flag set)..."
  if docker container inspect "$CONTAINER_NAME" > /dev/null 2>&1; then
    docker compose down -v
    print_status "Database reset"
  fi
fi

# Start Docker container
print_info "Starting PostgreSQL container..."
if docker container inspect "$CONTAINER_NAME" > /dev/null 2>&1 && docker ps --filter "name=$CONTAINER_NAME" | grep -q "$CONTAINER_NAME"; then
  print_status "PostgreSQL already running on port $HOST_PORT"
else
  docker compose up -d
  print_status "PostgreSQL started"
fi

# Wait for PostgreSQL to be ready
print_info "Waiting for PostgreSQL to be ready..."
max_attempts=30
attempt=0

while [ $attempt -lt $max_attempts ]; do
  if docker exec "$CONTAINER_NAME" pg_isready -U "$DB_USER" > /dev/null 2>&1; then
    print_status "PostgreSQL is ready"
    break
  fi
  attempt=$((attempt + 1))
  sleep 1
done

if [ $attempt -eq $max_attempts ]; then
  print_error "PostgreSQL failed to start within ${max_attempts}s"
  print_info "Check logs with: docker logs $CONTAINER_NAME"
  exit 1
fi

# Create .env file
print_info "Creating .env file..."
cat > .env << EOF
# Runs App Database Configuration
# Generated by dev-up.sh - do not commit to git

# Database Connection
JDBC_DATABASE_URL=jdbc:postgresql://localhost:$HOST_PORT/$DB_NAME
JDBC_DATABASE_USERNAME=$DB_USER
JDBC_DATABASE_PASSWORD=$DB_PASSWORD

# RabbitMQ (local defaults, adjust if needed)
RABBITMQ_HOST=localhost
RABBITMQ_PORT=5672
RABBITMQ_USERNAME=guest
RABBITMQ_PASSWORD=guest

# Application Server
SERVER_PORT=$APP_PORT

# Garmin Import Configuration
GARMIN_IMPORT_FOLDER=/data/garmin-fit-files
GARMIN_SYSTEM_USER_ID=10000

# SMTP Configuration (optional - for email features)
SMTP_HOST=smtp.gmail.com
SMTP_USERNAME=your-email@gmail.com
SMTP_PASSWORD=your-app-password

# Production flag
PRODUCTION=false
API_PATH=
EOF

print_status ".env file created"

# Verify database exists
print_info "Verifying database..."
if docker exec -i "$CONTAINER_NAME" psql -U "$DB_USER" -d "$DB_NAME" -c "SELECT 1;" > /dev/null 2>&1; then
  print_status "Database verified"
else
  print_error "Failed to verify database"
  exit 1
fi

# Print next steps
echo ""
echo "════════════════════════════════════════════════════════════════"
echo -e "${GREEN}✓ Runs App is ready!${NC}"
echo "════════════════════════════════════════════════════════════════"
echo ""
echo "Database Details:"
echo "  Host:     localhost"
echo "  Port:     $HOST_PORT"
echo "  Database: $DB_NAME"
echo "  User:     $DB_USER"
echo "  Password: $DB_PASSWORD"
echo ""
echo "Next Steps:"
echo "  1. Run the application:"
echo "     mvn spring-boot:run"
echo ""
echo "  2. Or start React dev server (in separate terminal):"
echo "     npm run devserver"
echo ""
echo "  3. Flyway migrations will run automatically on startup"
echo ""
echo "  4. Access the application:"
echo "     Frontend (dev): http://localhost:3000"
echo "     Backend API:    http://localhost:$APP_PORT"
echo "     Health Check:   http://localhost:$APP_PORT/actuator/health"
echo ""
echo "Useful Commands:"
echo "  Stop database:    docker compose down"
echo "  View logs:        docker logs $CONTAINER_NAME"
echo "  Connect via psql: psql -h localhost -p $HOST_PORT -U $DB_USER -d $DB_NAME"
echo "  Reset database:   ./dev-up.sh --reset"
echo ""
echo "════════════════════════════════════════════════════════════════"
echo ""
